// Regenerates apps/site/src/styles/tokens.generated.css from the UI's tokens.
//
// The marketing site is the product's colours on a web page, so it has no
// palette of its own. `apps/ui/src/theme/tokens.ts` stays the only file in the
// repository allowed to hold a raw colour value, exactly as its own header
// says, and this script carries those values across the one gap a TypeScript
// import cannot cross: Tailwind v4 reads its theme from CSS, at build time,
// and CSS cannot import a `.ts` file.
//
// So the same thing is done here that is done with the Rust domain types:
// generate, check the output in, and never edit it by hand. The site's
// `predev` and `prebuild` both run this, so the two cannot drift even if
// somebody forgets.
//
// Names are kebab-cased on the way out - `surfaceRaised` becomes
// `--color-surface-raised`, so the class is `bg-surface-raised`. The UI's
// classes stay camelCase because Tailwind v3 takes its theme from the
// JavaScript object's keys directly; here the key becomes a CSS custom
// property, and lower-case-with-dashes is the only spelling worth relying on.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "apps", "ui", "src", "theme", "tokens.ts");
const target = path.join(
  root,
  "apps",
  "site",
  "src",
  "styles",
  "tokens.generated.css",
);

const { colorTokens, fontStacks } = await importTokens(source);

const lines = [
  "/*",
  " * Generated by scripts/gen-site-theme.mjs from",
  " * apps/ui/src/theme/tokens.ts. Do not edit this file manually.",
  " *",
  " * Add a colour to the token file and re-run `npm run gen:theme`.",
  " */",
  "",
  "@theme {",
  ...Object.entries(colorTokens).map(
    ([name, value]) => `  --color-${kebab(name)}: ${value};`,
  ),
  "",
  ...Object.entries(fontStacks).map(
    ([name, stack]) => `  --font-${kebab(name)}: ${quoteStack(stack)};`,
  ),
  "}",
];

fs.writeFileSync(target, `${lines.join("\n")}\n`, "utf8");
console.log(
  `tokens.generated.css: ${Object.keys(colorTokens).length} colours, ` +
    `${Object.keys(fontStacks).length} font stacks`,
);

/**
 * Reads the token module without a TypeScript toolchain.
 *
 * The file is plain data - two `as const` object literals and one exported
 * type - so stripping the two pieces of TypeScript syntax it uses leaves
 * valid JavaScript, which Node imports from a data URL. Nothing is written to
 * disk and nothing is added to the dependency tree to read one object.
 */
async function importTokens(file) {
  const javascript = fs
    .readFileSync(file, "utf8")
    .replace(/^export type .*$/gm, "")
    .replace(/ as const/g, "");

  return import(`data:text/javascript,${encodeURIComponent(javascript)}`);
}

function kebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

/** A font stack is a CSS value, so every family with a space needs quoting. */
function quoteStack(stack) {
  return stack
    .map((family) => (family.includes(" ") ? `"${family}"` : family))
    .join(", ");
}
