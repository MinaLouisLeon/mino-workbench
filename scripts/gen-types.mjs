// Regenerates apps/ui/src/Types/generated from the Rust domain types.
//
// ts-rs writes one file per `#[derive(TS)]` type. The output is checked in so
// the UI type-checks without a Rust toolchain; run this whenever a type in
// crates/mino-core/src/types or error.rs changes.
//
// The barrel is written here rather than by ts-rs, which stopped emitting one.
// Leaving it out would make `generated/index.ts` a file somebody has to
// remember to hand-edit after adding a type - and a generated folder with one
// hand-maintained file in it is exactly the drift the "never edit generated
// types" rule exists to prevent.
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const exportDir = path.join(root, "apps", "ui", "src", "Types");
const generatedDir = path.join(exportDir, "generated");

const HEADER =
  "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.";

const result = spawnSync(
  "cargo",
  ["test", "-p", "mino-core", "--", "--quiet"],
  {
    cwd: root,
    stdio: "inherit",
    // ts-rs joins each type's `export_to = "generated/"` onto this directory.
    env: { ...process.env, TS_RS_EXPORT_DIR: exportDir },
  },
);

if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

writeBarrel();

/** One `export *` per generated module, sorted so the file is stable. */
function writeBarrel() {
  const modules = fs
    .readdirSync(generatedDir)
    .filter((name) => name.endsWith(".ts") && name !== "index.ts")
    .map((name) => name.slice(0, -3))
    .sort();

  const lines = [
    HEADER,
    ...modules.map((name) => `export * from "./${name}";`),
  ];
  fs.writeFileSync(
    path.join(generatedDir, "index.ts"),
    `${lines.join("\n")}\n`,
    "utf8",
  );
  console.log(`generated/index.ts: ${modules.length} types`);
}
